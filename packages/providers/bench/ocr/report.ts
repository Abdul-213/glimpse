// GLIM-64: the benchmark's markdown report (docs/benchmarks/ocr-results.md). Pure.
import { type CaseResult, type Corpus, percentile, type ScriptSummary, type Summary, THRESHOLDS } from "./metrics.ts";

export interface ReportInput {
	readonly summary: Summary;
	readonly results: readonly CaseResult[];
	readonly skipped: readonly string[];
	readonly machine: string;
	readonly initMs: number;
	readonly warmupMs: number;
	readonly iterations: number;
	readonly corpus: Corpus;
}

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;
const ms = (n: number) => `${Math.round(n)}`;
const esc = (s: string) => s.replaceAll("|", "\\|").replaceAll("\n", " ");

function scriptRow(name: string, s: ScriptSummary): string {
	return `| ${name} | ${s.cases} | ${pct(s.cer)} | ${s.wer === null ? "n/a" : pct(s.wer)} | ${pct(s.grouping)} | ${pct(s.order)} | ${pct(s.detection)} | ${ms(s.p50)} | ${ms(s.p90)} |`;
}

export function renderReport(r: ReportInput): string {
	const out: string[] = [];
	out.push("# OCR benchmark results");
	out.push("");
	out.push("Generated by `bun run bench:ocr` (GLIM-64); method and findings in [ocr.md](ocr.md). Do not edit by hand.");
	out.push("");
	out.push(`- Machine: ${r.machine}`);
	out.push(`- Engine: PaddleOCR PP-OCRv5 mobile (onnxruntime CPU), default options, rec cache off`);
	out.push(
		`- Corpus: ${r.corpus.cases.length} cases, ${r.results.length} run; ${r.iterations} warm runs per case after one first call`,
	);
	out.push(`- Provider init ${ms(r.initMs)} ms, warmup ${ms(r.warmupMs)} ms`);
	out.push(
		`- Gate (\`--check\`): per-script CER may rise by max(${THRESHOLDS.cerAbs * 100} points, ${THRESHOLDS.cerRel * 100}%); grouping and detection may fall ${THRESHOLDS.fractionDrop * 100} points; summed p50 may grow ${THRESHOLDS.latencyFactor}x`,
	);
	if (r.skipped.length > 0) out.push(`- Skipped: ${r.skipped.join("; ")}`);
	out.push("");
	out.push("## Per script");
	out.push("");
	out.push("| Script | Cases | CER | WER | Grouping exact | Order right | Detection | p50 ms | p90 ms |");
	out.push("|---|---|---|---|---|---|---|---|---|");
	for (const [name, s] of Object.entries(r.summary.scripts)) out.push(scriptRow(name, s));
	out.push(scriptRow("**All**", r.summary.all));
	out.push("");
	out.push(`Summed warm p50 over all cases: ${ms(r.summary.totalP50)} ms.`);
	out.push("");
	out.push("## Per case");
	out.push("");
	out.push(
		"| Case | Kind | Size | CER | WER | Blocks exact / truth (got) | Order | Detection | First ms | p50 ms | p90 ms |",
	);
	out.push("|---|---|---|---|---|---|---|---|---|---|---|");
	const byId = new Map(r.corpus.cases.map((c) => [c.id, c]));
	for (const c of r.results) {
		const meta = byId.get(c.id);
		const s = c.score;
		out.push(
			`| ${c.id} | ${c.kind} | ${meta ? `${meta.width}x${meta.height}` : ""} | ${pct(s.cer)} | ${s.wer === null ? "n/a" : pct(s.wer)} | ${s.blocks.exact} / ${s.blocks.truth} (${s.blocks.got}) | ${s.orderCorrect ? "ok" : "wrong"} | ${s.detection.correct} / ${s.detection.total} | ${ms(c.firstMs)} | ${ms(percentile(c.runs, 0.5))} | ${ms(percentile(c.runs, 0.9))} |`,
		);
	}
	out.push("");
	out.push("## Differences");
	out.push("");
	out.push("Every line that wasn't read exactly, every extra line, every grouping and detection miss.");
	out.push("");
	let any = false;
	for (const c of r.results) {
		const s = c.score;
		const notes: string[] = [];
		for (const l of s.lines) {
			if (l.charEdits > 0)
				notes.push(`- line: \`${esc(l.truth)}\` read as \`${esc(l.got) || "(nothing)"}\` (${l.charEdits} edits)`);
		}
		for (const e of s.extra) notes.push(`- extra line: \`${esc(e)}\``);
		for (const g of s.blocks.notes) notes.push(`- grouping: ${esc(g)}`);
		if (!s.orderCorrect) notes.push("- reading order differs from the ground truth");
		for (const m of s.detection.misses)
			notes.push(`- detection: \`${esc(m.text)}\` expected ${m.expected}, got ${m.got}`);
		if (notes.length === 0) continue;
		any = true;
		out.push(`**${c.id}**`);
		out.push("");
		out.push(...notes);
		out.push("");
	}
	if (!any) out.push("None.");
	return `${out.join("\n").trimEnd()}\n`;
}
