// GLIM-66: what Live costs in CPU, for the budget in docs/benchmarks/live-cpu.md.
//
//   bun app/scripts/live-cpu.ts            change detection per grab by region size + the
//                                          harness scenarios on virtual time (fast)
//   bun app/scripts/live-cpu.ts --paddle   also both scenarios in real time with real
//                                          PaddleOCR (models from `bun run models`; ~30 s)
//
// Prints markdown. CPU is process CPU (`process.cpuUsage`, user + system, all threads), so the
// real-OCR rows include the OCR Worker. The file capture backend decodes PNGs, which a real
// capture backend doesn't, so capture is listed apart and left out of the per-minute figure.
import { availableParallelism, cpus } from "node:os";
import {
	ChangeDetector,
	type LanguageCode,
	LIVE_BUDGET_DEFAULTS,
	languageCode,
	type OcrProvider,
	systemTimers,
} from "@glimpse/core";
import { makeImage } from "@glimpse/core/testing";
import { createFileCaptureSource } from "../src/bun/services/capture/file.ts";
import {
	LIVE_SCENARIO_DIR,
	LIVE_SCENARIO_LINES,
	LIVE_SCENARIO_RECT,
	MOVING_VIDEO_DIR,
	MOVING_VIDEO_TIMELINE,
} from "../src/harness/live-scenario.ts";
import { runLiveSession } from "../src/harness/live-session.ts";
import { fakeTranslator, frameKeyedOcr, paddleOcr, subtitleOcr } from "../src/harness/providers.ts";

const cpuMs = () => {
	const u = process.cpuUsage();
	return (u.user + u.system) / 1000;
};
const f1 = (n: number) => n.toFixed(1);
const f2 = (n: number) => n.toFixed(2);
const pct = (n: number) => `${(n * 100).toFixed(1)} %`;

// ---- 1. change detection per grab, by region size -------------------------------------------

type Rgb = readonly [number, number, number];
const video =
	(frame: number) =>
	(x: number, y: number): Rgb => {
		const c = ((Math.floor(x / 8) * 7 + Math.floor(y / 8) * 13 + frame * 101) * 2654435761) >>> 0;
		return [40 + (c % 150), 40 + ((c >>> 8) % 150), 40 + ((c >>> 16) % 150)];
	};

function detectionCost(width: number, height: number, scale: number, mode: "same" | "changed" | "focus"): number {
	const frames = [0, 1, 2].map((i) => makeImage(width, height, mode === "same" ? video(0) : video(i)));
	const d = new ChangeDetector({ diffThreshold: 0.02, stabilityMs: 300 });
	const N = 40;
	let t = 0;
	const feed = (i: number) => {
		t += 250;
		return d.feed({
			...(frames[i % 3] as (typeof frames)[number]),
			scale,
			sequence: mode === "same" ? 1 : i + 1,
			capturedAt: t,
		});
	};
	// Warm up the JIT, and for `focus` run long enough to enter text focus (1.5 s of motion).
	for (let i = 0; i < 12; i++) feed(i);
	if (mode === "focus" && !d.focused) throw new Error("focus not entered");
	const c0 = cpuMs();
	for (let i = 12; i < 12 + N; i++) feed(i);
	return (cpuMs() - c0) / N;
}

const out: string[] = [];
out.push("# Live CPU measurements (GLIM-66)");
out.push("");
out.push(
	`Generated by \`bun app/scripts/live-cpu.ts${process.argv.includes("--paddle") ? " --paddle" : ""}\`. Machine: ${cpus()[0]?.model.trim() ?? "?"}, ${availableParallelism()} threads, Bun ${Bun.version}.`,
);
out.push("");
out.push("## Change detection per grab (main-process CPU)");
out.push("");
out.push("| Region (device px) | Unchanged frame | Changed (whole region) | Text focus | Focus at 4 fps |");
out.push("|---|---|---|---|---|");
for (const [w, h, s, label] of [
	[400, 100, 1, "400x100 (a dialogue line)"],
	[800, 240, 1, "800x240 (a subtitle strip)"],
	[1280, 720, 1, "1280x720 (a video at 1x)"],
	[2560, 1440, 2, "2560x1440 (the same at 2x, sampled per logical px)"],
	[1920, 1080, 1, "1920x1080 (a whole 1x screen)"],
] as const) {
	const same = detectionCost(w, h, s, "same");
	const changed = detectionCost(w, h, s, "changed");
	const focus = detectionCost(w, h, s, "focus");
	out.push(
		`| ${label} | ${f2(same)} ms | ${f2(changed)} ms | ${f2(focus)} ms | ${pct((focus * 4) / 1000)} of a core |`,
	);
}

// ---- 2. the harness scenarios ---------------------------------------------------------------

interface Row {
	readonly name: string;
	readonly seconds: number;
	readonly grabs: number;
	readonly ocr: number;
	readonly detectMsPerGrab: number;
	readonly captureMsPerGrab: number;
	readonly cpuMsPerMinute: number;
	readonly budget: string;
}

async function scenario(
	name: string,
	movingVideo: boolean,
	ocr: OcrProvider,
	realtime: boolean,
	sources: readonly LanguageCode[],
): Promise<Row> {
	const dir = movingVideo ? MOVING_VIDEO_DIR : LIVE_SCENARIO_DIR;
	const timers = realtime ? systemTimers : undefined;
	const { ManualTimers } = await import("@glimpse/core/testing");
	const t = timers ?? new ManualTimers();
	const source = createFileCaptureSource(dir, { advance: "timed", now: t.now });
	const translator = await fakeTranslator();
	const durationMs = movingVideo ? 12_000 : (source.durationMs ?? 10_000) + 2000;
	try {
		const r = await runLiveSession(source, LIVE_SCENARIO_RECT, {
			ocr,
			translation: translator.provider,
			to: languageCode("en"),
			sources,
			fps: 4,
			diffThreshold: 0.02,
			stabilityMs: 300,
			durationMs,
			timers: t,
			cpuMicros: () => cpuMs() * 1000,
		});
		const s = r.stats;
		const cpuTotal = (r.cpuMsPerGrab ?? 0) * s.grabs;
		const captureTotal = s.meanGrabMs * s.grabs;
		// Per minute of Live: everything but the PNG decoding of the file backend.
		const perMinute = ((cpuTotal - captureTotal) / durationMs) * 60_000;
		return {
			name,
			seconds: durationMs / 1000,
			grabs: s.grabs,
			ocr: s.ocrRuns,
			detectMsPerGrab: s.meanDetectMs,
			captureMsPerGrab: s.meanGrabMs,
			cpuMsPerMinute: perMinute,
			budget: s.budget ? `level ${s.budget.level}` : "off",
		};
	} finally {
		await translator.dispose();
	}
}

const staticLines = Object.values(LIVE_SCENARIO_LINES);
const videoLines = [
	...new Set(MOVING_VIDEO_TIMELINE.flatMap((s) => (s.key === "none" ? [] : [LIVE_SCENARIO_LINES[s.key]]))),
];
const rows: Row[] = [];
{
	const o = frameKeyedOcr(staticLines);
	await o.init();
	rows.push(await scenario("GLIM-58 static scene, scripted OCR (virtual time)", false, o, false, []));
	const v = subtitleOcr(videoLines);
	await v.init();
	rows.push(await scenario("GLIM-114 subtitles over moving video, scripted OCR (virtual time)", true, v, false, []));
}
if (process.argv.includes("--paddle")) {
	const p = await paddleOcr();
	try {
		const ja = [languageCode("ja")];
		rows.push(await scenario("GLIM-58 static scene, PaddleOCR (real time)", false, p, true, ja));
		rows.push(await scenario("GLIM-114 subtitles over moving video, PaddleOCR (real time)", true, p, true, ja));
	} finally {
		await p.dispose();
	}
}

out.push("");
out.push("## Harness scenarios (800x90 subtitle strip, 4 fps)");
out.push("");
out.push(
	"| Scenario | Length | Grabs | OCR runs | Change detection per grab | Capture (file backend) per grab | CPU per minute of Live | Share of a core | Budget |",
);
out.push("|---|---|---|---|---|---|---|---|---|");
for (const r of rows) {
	out.push(
		`| ${r.name} | ${r.seconds} s | ${r.grabs} | ${r.ocr} | ${f2(r.detectMsPerGrab)} ms | ${f2(r.captureMsPerGrab)} ms | ${f1(r.cpuMsPerMinute / 1000)} s | ${pct(r.cpuMsPerMinute / 60_000)} | ${r.budget} |`,
	);
}
out.push("");
out.push(
	`Budget (live-budget.ts): ${pct(LIVE_BUDGET_DEFAULTS.shareOfCore)} of one core over ${LIVE_BUDGET_DEFAULTS.windowMs / 1000} s.`,
);
console.log(out.join("\n"));
